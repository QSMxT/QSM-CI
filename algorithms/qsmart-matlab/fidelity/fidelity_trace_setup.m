function tdir = fidelity_trace_setup(shimdir, logdir)
% In-pipeline shim check. Puts a tracer in front of every shim name: each call QSMART, STI
% Suite's .p code or recon.m makes runs the shim (whose result is returned, so the pipeline
% computes exactly what the container computes) AND the licensed toolbox function on the same
% arguments, and logs the comparison to LOGDIR/trace.tsv. The first call per shim whose results
% differ has its arguments saved to LOGDIR/repro_<shim>.mat as a minimal repro.
%
% Needs licensed MATLAB with the toolboxes; shims/ itself must NOT be on the path.
    global QSMCI_FIDELITY %#ok<GVMIS>
    tdir = tempname; mkdir(tdir);
    names = fidelity_shim_copies(shimdir, tdir);
    for k = 1:numel(names)
        assert(startsWith(which(names{k}), fullfile(matlabroot, 'toolbox')), ...
            '%s does not resolve to the toolbox (%s)', names{k}, which(names{k}));
        fid = fopen(fullfile(tdir, [names{k} '.m']), 'w');
        fprintf(fid, ['function varargout = %s(varargin)\n' ...
                      '%% QSM-CI fidelity tracer (generated by fidelity_trace_setup.m)\n' ...
                      'varargout = fidelity_trace_call(''%s'', varargin, max(nargout, 1));\n' ...
                      'end\n'], names{k}, names{k});
        fclose(fid);
    end
    if ~exist(logdir, 'dir'), mkdir(logdir); end
    QSMCI_FIDELITY = struct('tdir', tdir, 'logdir', logdir, 'saved', {{}}, 'n', 0, ...
                            'fid', fopen(fullfile(logdir, 'trace.tsv'), 'w'));
    fprintf(QSMCI_FIDELITY.fid, ['shim\tcall\tcaller\targs\tout_class\tout_size\tidentical\t' ...
                                 'maxabs\tmaxrel\tndiff\tnumel\tt_shim\tt_ref\tnote\n']);
    addpath(tdir);
    rehash;
end
